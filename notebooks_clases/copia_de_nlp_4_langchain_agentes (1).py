SQLITE_PATH = Path("demo.db").resolve()

def bootstrap_sqlite(path: Path = SQLITE_PATH) -> None:
    """Crea la base de ejemplo e inserta datos solamente si la tabla está vacía."""
    with sqlite3.connect(path) as con:
        cur = con.cursor()
        cur.execute("""CREATE TABLE IF NOT EXISTS gastos(
            id INTEGER PRIMARY KEY,
            categoria TEXT,
            monto REAL,
            fecha TEXT
        )""")
        cur.execute("SELECT COUNT(*) FROM gastos")
        if cur.fetchone()[0] == 0:
            cur.executemany(
                "INSERT INTO gastos(categoria, monto, fecha) VALUES (?, ?, ?)",
                [
                    ("comida", 2500.0, "2025-08-30"),
                    ("transporte", 1800.0, "2025-09-01"),
                    ("comida", 3200.5, "2025-09-02"),
                ],
            )

bootstrap_sqlite()

"""### Tools

Una herramienta es una función con:

- un nombre;
- una descripción —tomada del docstring—;
- un esquema de argumentos derivado de sus tipos;
- una implementación ejecutada por la aplicación, no por el LLM.


"""

MAX_ROWS = 50

def _readonly_connection() -> sqlite3.Connection:
    # mode=ro agrega una segunda barrera: SQLite no permitirá escrituras.
    return sqlite3.connect(f"file:{SQLITE_PATH}?mode=ro", uri=True)

@tool
def sql_schema() -> str:
    """Devuelve las tablas y columnas disponibles en la base SQLite de gastos."""
    with _readonly_connection() as con:
        cur = con.cursor()
        cur.execute(
            "SELECT name FROM sqlite_master "
            "WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name"
        )
        tables = [row[0] for row in cur.fetchall()]
        lines = []
        for table in tables:
            # Los nombres provienen de sqlite_master, no de la entrada del usuario.
            cur.execute(f'PRAGMA table_info("{table}")')
            columns = ", ".join(f"{col[1]} {col[2]}" for col in cur.fetchall())
            lines.append(f"- {table}: {columns}")
    return "Esquema:\n" + ("\n".join(lines) if lines else "(sin tablas)")

@tool
def sql_query(query: str) -> str:
    """Ejecuta una única consulta SELECT de solo lectura sobre la tabla de gastos."""
    q = query.strip()
    if q.endswith(";"):
        q = q[:-1].rstrip()
    if ";" in q:
        return "Por seguridad, solo se permite una sentencia por llamada."
    if not re.match(r"(?is)^select\b", q):
        return "Solo se permiten consultas SELECT."
    forbidden = r"\b(insert|update|delete|drop|alter|attach|create|replace|vacuum|pragma)\b"
    if re.search(forbidden, q, flags=re.I):
        return "Se detectó una palabra clave no permitida para lectura segura."

    try:
        with _readonly_connection() as con:
            cur = con.cursor()
            cur.execute(q)
            rows = cur.fetchmany(MAX_ROWS + 1)
            columns = [desc[0] for desc in cur.description] if cur.description else []
    except sqlite3.Error as exc:
        return f"Error al ejecutar la consulta: {exc}"

    if not rows:
        return "(sin resultados)"
    truncated = len(rows) > MAX_ROWS
    rows = rows[:MAX_ROWS]
    header = " | ".join(columns)
    separator = "-|-".join("-" * len(column) for column in columns)
    body = "\n".join(" | ".join(str(value) for value in row) for row in rows)
    note = f"\n… (mostrando primeras {MAX_ROWS} filas)" if truncated else ""
    return f"{header}\n{separator}\n{body}{note}"

_BINARY_OPERATORS = {
    ast.Add: operator.add,
    ast.Sub: operator.sub,
    ast.Mult: operator.mul,
    ast.Div: operator.truediv,
    ast.Mod: operator.mod,
    ast.Pow: operator.pow,
}
_UNARY_OPERATORS = {ast.UAdd: operator.pos, ast.USub: operator.neg}

def _evaluate_arithmetic(node: ast.AST) -> int | float:
    if isinstance(node, ast.Expression):
        return _evaluate_arithmetic(node.body)
    if isinstance(node, ast.Constant) and type(node.value) in (int, float):
        return node.value
    if isinstance(node, ast.UnaryOp) and type(node.op) in _UNARY_OPERATORS:
        return _UNARY_OPERATORS[type(node.op)](_evaluate_arithmetic(node.operand))
    if isinstance(node, ast.BinOp) and type(node.op) in _BINARY_OPERATORS:
        left = _evaluate_arithmetic(node.left)
        right = _evaluate_arithmetic(node.right)
        if isinstance(node.op, ast.Pow) and abs(right) > 10:
            raise ValueError("El exponente debe estar entre -10 y 10.")
        return _BINARY_OPERATORS[type(node.op)](left, right)
    raise ValueError("La expresión contiene una operación no permitida.")

@tool
def calc(expression: str) -> str:
    """Calcula una expresión aritmética con números, paréntesis y +, -, *, /, %, **."""
    if len(expression) > 100:
        return "La expresión es demasiado larga."
    try:
        tree = ast.parse(expression, mode="eval")
        return str(_evaluate_arithmetic(tree))
    except (SyntaxError, ValueError, TypeError, ZeroDivisionError) as exc:
        return f"Error de cálculo: {exc}"

@tool
def todo_brainstorm(topic: str) -> str:
    """Propone una lista breve de tareas para organizar un tema."""
    items = [
        f"Definir objetivo concreto para: {topic}",
        f"Listar 3 tareas clave sobre: {topic}",
        f"Identificar bloqueo principal en: {topic}",
        f"Estimar esfuerzo y responsables para: {topic}",
    ]
    return "\n".join(f"- {item}" for item in items)

TOOLS = [sql_schema, sql_query, calc, todo_brainstorm]

"""### Comprobación local de las tools

Estas pruebas no requieren un LLM. Permiten separar errores de las herramientas de errores en las decisiones del agente.

"""

assert calc.invoke({"expression": "200 * 18 + 750"}) == "4350"
assert "5700.5" in sql_query.invoke({
    "query": "SELECT SUM(monto) AS total FROM gastos WHERE categoria = 'comida';"
})
assert "solo se permite una sentencia" in sql_query.invoke({
    "query": "SELECT 1; SELECT 2;"
})
assert "gastos" in sql_schema.invoke({})
print("Tools verificadas correctamente.")

