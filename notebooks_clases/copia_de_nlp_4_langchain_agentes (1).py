"""## Creación del agente y del ciclo de ejecución

`create_agent` construye el ciclo completo sobre LangGraph:

`modelo → decisión → herramienta → observación en el estado → modelo`

`InMemorySaver` conserva el estado de cada conversación durante la vida del proceso. Para producción se reemplazaría por persistencia duradera.

"""

llm = make_llm(BACKEND)
checkpointer = InMemorySaver()

agent = create_agent(
    model=llm,
    tools=TOOLS,
    system_prompt=SYSTEM_PROMPT,
    checkpointer=checkpointer,
)

"""## Sesión e interacción

La función siguiente puede mostrar las transiciones observables sin solicitar el razonamiento privado del modelo.

"""

THREAD_ID = "sesion_demo_1"

def _message_content(message) -> str:
    content = message.content
    return content if isinstance(content, str) else str(content)

def ask(message: str, *, thread_id: str = THREAD_ID, show_steps: bool = True) -> str:
    config = {
        "configurable": {"thread_id": thread_id},
        "recursion_limit": 12,
    }
    result = agent.invoke(
        {"messages": [{"role": "user", "content": message}]},
        config=config,
    )

    if show_steps:
        print("\n--- TRAZA OBSERVABLE ---")
        for item in result["messages"]:
            if getattr(item, "tool_calls", None):
                for call in item.tool_calls:
                    print(f"Decisión: llamar {call['name']} con {call['args']}")
            if getattr(item, "type", None) == "tool":
                print(f"Observación de {item.name}: {_message_content(item)}")

    answer = _message_content(result["messages"][-1])
    print("\n--- RESPUESTA ---\n", answer)
    return answer

