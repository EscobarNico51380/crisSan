# 3.4) Cadena de RAG con historial - LangChain moderno

from langchain_core.prompts import ChatPromptTemplate, MessagesPlaceholder
from langchain_core.output_parsers import StrOutputParser
from langchain_core.runnables import RunnableLambda, RunnablePassthrough


llm = llm_factory()


# ============================================================
# 1. Prompt para reformular la pregunta usando el historial
# ============================================================

contextualize_q_prompt = ChatPromptTemplate.from_messages([
    (
        "system",
        "Reescribe la consulta del usuario para que pueda utilizarse "
        "de forma independiente en una búsqueda documental. "
        "Ten en cuenta el historial de conversación. "
        "Devuelve solamente la consulta reformulada."
    ),
    MessagesPlaceholder("chat_history"),
    ("human", "{input}")
])


# ============================================================
# 2. Cadena para reformular la consulta
# ============================================================

contextualize_chain = (
    contextualize_q_prompt
    | llm
    | StrOutputParser()
)


# ============================================================
# 3. Recuperar documentos
# ============================================================

def retrieve_documents(data):

    # Si existe historial, reformulamos la pregunta
    if data.get("chat_history"):

        query = contextualize_chain.invoke({
            "input": data["input"],
            "chat_history": data["chat_history"]
        })

    else:

        query = data["input"]


    # --------------------------------------------------------
    # IMPORTANTE:
    # Garantizamos que el retriever reciba un str
    # --------------------------------------------------------

    query = str(query)


    # Información útil para la demostración
    print("\n==============================")
    print("CONSULTA AL RETRIEVER:")
    print(repr(query))
    print("TIPO:", type(query))
    print("==============================\n")


    # Buscamos documentos relevantes
    docs = retriever.invoke(query)

    return docs


# ============================================================
# 4. Convertir documentos recuperados a texto
# ============================================================

def format_docs(docs):

    return "\n\n".join(
        doc.page_content
        for doc in docs
    )


# ============================================================
# 5. Prompt final del RAG
# ============================================================

qa_prompt = ChatPromptTemplate.from_messages([
    (
        "system",
        "Eres un asistente experto. "
        "Usa EXCLUSIVAMENTE el contexto proporcionado para responder "
        "en español. "
        "Si la respuesta no está en el contexto, di claramente que "
        "no aparece.\n\n"
        "===== CONTEXTO =====\n"
        "{context}\n"
        "====================="
    ),

    MessagesPlaceholder("chat_history"),

    ("human", "{input}")
])


# ============================================================
# 6. Construimos la cadena RAG
# ============================================================

rag_chain = (
    RunnablePassthrough.assign(
        context=(
            RunnableLambda(retrieve_documents)
            | RunnableLambda(format_docs)
        )
    )
    | qa_prompt
    | llm
    | StrOutputParser()
)


print("Cadena RAG construida ✓")

# 3.5) RAG conversacional con memoria usando LangGraph

import time

from typing import TypedDict, Annotated

from langchain_core.messages import BaseMessage
from langgraph.graph import StateGraph, START, END
from langgraph.graph.message import add_messages
from langgraph.checkpoint.memory import MemorySaver


# ============================================================
# 1. Estado de la conversación
# ============================================================

class RAGState(TypedDict):
    messages: Annotated[list[BaseMessage], add_messages]


# ============================================================
# 2. Función auxiliar con reintentos
# ============================================================

def ejecutar_rag_con_reintentos(
    pregunta,
    chat_history,
    max_retries=3
):
    """
    Ejecuta el RAG y reintenta ante errores temporales
    del servicio de embeddings / Gemini.
    """

    for intento in range(max_retries):

        try:

            return rag_chain.invoke({
                "input": pregunta,
                "chat_history": chat_history
            })

        except Exception as e:

            # Si ya agotamos los intentos,
            # propagamos el error original
            if intento == max_retries - 1:
                raise

            # Backoff exponencial:
            # 1s, 2s, 4s...
            espera = 2 ** intento

            print(
                f"⚠ Error temporal de Gemini "
                f"(intento {intento + 1}/{max_retries})."
            )

            print(
                f"Reintentando en {espera} segundo(s)..."
            )

            time.sleep(espera)


# ============================================================
# 3. Nodo RAG
# ============================================================

def rag_node(state: RAGState):

    messages = state["messages"]

    # Último mensaje = pregunta actual
    pregunta = messages[-1].content

    # Todo lo anterior constituye el historial
    chat_history = messages[:-1]

    # Ejecutamos el RAG con reintentos
    respuesta = ejecutar_rag_con_reintentos(
        pregunta=pregunta,
        chat_history=chat_history
    )

    # LangGraph agregará la respuesta al historial
    return {
        "messages": [
            ("assistant", respuesta)
        ]
    }


# ============================================================
# 4. Construcción del grafo
# ============================================================

builder = StateGraph(RAGState)

builder.add_node(
    "rag",
    rag_node
)

builder.add_edge(
    START,
    "rag"
)

builder.add_edge(
    "rag",
    END
)


# ============================================================
# 5. Memoria
# ============================================================

memory = MemorySaver()

rag_with_history = builder.compile(
    checkpointer=memory
)


# ============================================================
# 6. Identificador de la conversación
# ============================================================

config = {
    "configurable": {
        "thread_id": "demo"
    }
}


# ============================================================
# 7. Función para conversar
# ============================================================

def conversar(pregunta: str):

    respuesta = rag_with_history.invoke(
        {
            "messages": [
                ("user", pregunta)
            ]
        },
        config=config
    )

    ultimo_mensaje = respuesta["messages"][-1]

    print("→", ultimo_mensaje.content)


# ============================================================
# 8. Demostración multi-turno
# ============================================================

print("Pregunta 1: ¿Qué es RAG?")
conversar("¿Qué es RAG?")


print("\nPregunta 2: ¿Y cómo se relaciona con LangChain?")
conversar("¿Y cómo se relaciona con LangChain?")


print("\nPregunta 3: ¿Dónde mencionaste los retrievers?")
conversar("¿Dónde mencionaste los retrievers?")


# ============================================================
# 9. Inspeccionar la memoria
# ============================================================

estado = rag_with_history.get_state(config)

print("\n--- Memoria acumulada ---")

for mensaje in estado.values["messages"]:

    print(
        type(mensaje).__name__,
        "→",
        mensaje.content
    )

